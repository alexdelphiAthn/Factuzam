-- ============================================================================
-- Facturacion periodica de operaciones de caja VE y TA
-- ============================================================================
-- VE se materializa como proforma interna no fiscal. TA genera una factura
-- normal y esta tabla auxiliar conserva el vinculo con cada operacion.
-- Las lineas AJUSTE compensan una VE incluida que despues fue rectificada o
-- sustituida. El script es idempotente y no modifica el dump modelo.
-- ============================================================================
CREATE TABLE IF NOT EXISTS `fza_facturacion_caja_periodos` (
  `ID_FACPER` bigint(20) NOT NULL AUTO_INCREMENT,
  `MODALIDAD_FACPER` varchar(2) NOT NULL,
  `CODIGO_EMP_ORIGEN_FACPER` varchar(10) NULL DEFAULT NULL,
  `CODIGO_EMP_DESTINO_FACPER` varchar(10) NOT NULL,
  `FECHA_DESDE_FACPER` date NOT NULL,
  `FECHA_HASTA_FACPER` date NOT NULL,
  `ESTADO_FACPER` varchar(20) NOT NULL DEFAULT 'ABIERTO',
  `CANTIDAD_DOCUMENTOS_FACPER` int(11) NOT NULL DEFAULT '0',
  `CANTIDAD_OPERACIONES_FACPER` int(11) NOT NULL DEFAULT '0',
  `CANTIDAD_AJUSTES_FACPER` int(11) NOT NULL DEFAULT '0',
  `INSTANTE_ALTA` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `INSTANTE_MODIF` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,
  `USUARIO_ALTA` varchar(100) NOT NULL,
  `USUARIO_MODIF` varchar(100) NOT NULL,
  PRIMARY KEY (`ID_FACPER`),
  INDEX `IDX_FACPER_REVISION` (
    `MODALIDAD_FACPER`, `CODIGO_EMP_ORIGEN_FACPER`,
    `CODIGO_EMP_DESTINO_FACPER`,
    `FECHA_DESDE_FACPER`, `FECHA_HASTA_FACPER`),
  INDEX `IDX_FACPER_ESTADO` (`ESTADO_FACPER`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci;
