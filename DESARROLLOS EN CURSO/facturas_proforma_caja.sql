-- Un TA legado podia reunir varias emisoras en un mismo periodo. Solo se
-- rellena el origen singular; NULL conserva el significado VARIAS/SIN RASTRO.
UPDATE fza_facturacion_caja_periodos P
JOIN (
  SELECT ID_FACPER_FACOP,
         MIN(CODIGO_EMP_ORIGEN_FACOP) AS CODIGO_EMP_ORIGEN
    FROM fza_facturas_operaciones_caja
   WHERE ID_FACPER_FACOP IS NOT NULL
   GROUP BY ID_FACPER_FACOP
  HAVING COUNT(DISTINCT CODIGO_EMP_ORIGEN_FACOP) = 1
) O ON O.ID_FACPER_FACOP = P.ID_FACPER
   SET P.CODIGO_EMP_ORIGEN_FACPER = O.CODIGO_EMP_ORIGEN
 WHERE P.MODALIDAD_FACPER = 'TA'
   AND P.CODIGO_EMP_ORIGEN_FACPER IS NULL;
SET @sExisteIdx = (
  SELECT COUNT(*) FROM INFORMATION_SCHEMA.STATISTICS
   WHERE TABLE_SCHEMA = DATABASE()
     AND TABLE_NAME = 'fza_facturas_operaciones_caja'
     AND INDEX_NAME = 'IDX_FACOP_PERIODO');
SET @sSql = IF(@sExisteIdx = 0,
  'ALTER TABLE fza_facturas_operaciones_caja
     ADD INDEX IDX_FACOP_PERIODO (ID_FACPER_FACOP)',
  'SELECT 1');
PREPARE stmt FROM @sSql;
EXECUTE stmt;
