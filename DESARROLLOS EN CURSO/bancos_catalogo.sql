--
-- Codigo de entidad espanol de 4 digitos (NRBE del Banco de Espana) + nombre
-- + BIC/SWIFT. Sirve para:
--   * Deducir la entidad a partir del IBAN al dar de alta un banco de empresa
--     (fza_empresas_bancos.CODIGO_BAN_EMPBAN).
--   * Mostrar el nombre del banco sin teclearlo.
