-- el usuario haya cambiado salvo los del catalogo base (ON DUPLICATE KEY).
--
-- Idempotente (INFORMATION_SCHEMA para la tabla, ON DUPLICATE KEY para la
-- semilla). NO toca factuzam_original.sql.
-- ============================================================================
-- ----------------------------------------------------------------------------
-- 1. fza_bancos (BAN): catalogo de entidades.
-- ----------------------------------------------------------------------------
SET @tab_exists := (
  SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES
   WHERE TABLE_SCHEMA = DATABASE()
     AND TABLE_NAME   = 'fza_bancos'
);
SET @ddl := IF(@tab_exists = 0,
  'CREATE TABLE `fza_bancos` ('
  '  `CODIGO_BAN`    varchar(4)   NOT NULL'
  '       COMMENT ''Codigo de entidad NRBE de 4 digitos'','
  '  `NOMBRE_BAN`    varchar(100) NOT NULL,'
  '  `BIC_BAN`       varchar(11)  NULL DEFAULT NULL'
  '       COMMENT ''BIC/SWIFT de la oficina central (8 u 11)'','
  '  `ESACTIVO_BAN`  varchar(1)   NOT NULL DEFAULT ''S'','
  '  `INSTANTE_MODIF` timestamp NOT NULL'
  '       DEFAULT current_timestamp() ON UPDATE current_timestamp(),'
  '  `INSTANTE_ALTA`  timestamp NOT NULL'
  '       DEFAULT ''0000-00-00 00:00:00'','
  '  `USUARIO_ALTA`   varchar(100) NOT NULL,'
  '  `USUARIO_MODIF`  varchar(100) NOT NULL,'
  '  PRIMARY KEY (`CODIGO_BAN`)'
  ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci',
  'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
