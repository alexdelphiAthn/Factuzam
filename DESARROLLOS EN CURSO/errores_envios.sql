  (`USUARIO_GRUPO_PERM`, `CODIGO_PERM`, `VALOR_PERM`, `DESCRIPCION_PERM`,
   `INSTANTE_ALTA`, `USUARIO_ALTA`)
SELECT 'Todos', 'menu.ErroresEnvios', 'S', 'Envío de errores',
       CURRENT_TIMESTAMP, 'SISTEMA'
